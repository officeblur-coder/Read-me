// Precomputes SVG paths for Romanian counties so the app ships no GIS runtime.
// Source: click_that_hood romania.geojson (county polygons). Run: npm run geo
import { readFileSync, writeFileSync } from 'node:fs';
import { geoMercator, geoPath } from 'd3-geo';

const W = 1000, H = 720;
const src = JSON.parse(readFileSync(new URL('./romania-counties.geojson', import.meta.url)));

const NAMES = {
  'Alba': 'Alba', 'Arad': 'Arad', 'Arges': 'Argeș', 'Bacau': 'Bacău', 'Bihor': 'Bihor',
  'Bistrita-Nasaud': 'Bistrița-Năsăud', 'Botosani': 'Botoșani', 'Braila': 'Brăila', 'Brasov': 'Brașov',
  'Bucharest': 'București', 'Bucuresti': 'București', 'Buzau': 'Buzău', 'Calarasi': 'Călărași',
  'Caras-Severin': 'Caraș-Severin', 'Cluj': 'Cluj', 'Constanta': 'Constanța', 'Covasna': 'Covasna',
  'Dambovita': 'Dâmbovița', 'Dimbovita': 'Dâmbovița', 'Dolj': 'Dolj', 'Galati': 'Galați', 'Giurgiu': 'Giurgiu',
  'Gorj': 'Gorj', 'Harghita': 'Harghita', 'Hunedoara': 'Hunedoara', 'Ialomita': 'Ialomița', 'Iasi': 'Iași',
  'Ilfov': 'Ilfov', 'Maramures': 'Maramureș', 'Mehedinti': 'Mehedinți', 'Mures': 'Mureș', 'Neamt': 'Neamț',
  'Olt': 'Olt', 'Prahova': 'Prahova', 'Salaj': 'Sălaj', 'Satu Mare': 'Satu Mare', 'Sibiu': 'Sibiu',
  'Suceava': 'Suceava', 'Teleorman': 'Teleorman', 'Timis': 'Timiș', 'Tulcea': 'Tulcea', 'Valcea': 'Vâlcea',
  'Vilcea': 'Vâlcea', 'Vaslui': 'Vaslui', 'Vrancea': 'Vrancea',
};

const projection = geoMercator().fitExtent([[12, 12], [W - 12, H - 12]], src);
const path = geoPath(projection).digits(1);

const counties = src.features.map((f) => {
  const raw = f.properties.name;
  const name = NAMES[raw];
  if (!name) throw new Error(`Unknown county: ${raw}`);
  // Light simplification: drop vertices closer than 2.2 px to the previous kept one.
  const simplified = {
    ...f,
    geometry: {
      ...f.geometry,
      coordinates: f.geometry.type === 'Polygon'
        ? simplifyPoly(f.geometry.coordinates)
        : f.geometry.coordinates.map(simplifyPoly),
    },
  };
  const [cx, cy] = path.centroid(simplified);
  return { name, d: path(simplified), cx: +cx.toFixed(1), cy: +cy.toFixed(1) };
});

function simplifyPoly(rings) {
  return rings.map((ring) => {
    const out = [];
    let last = null;
    for (const pt of ring) {
      const p = projection(pt);
      if (!last || Math.hypot(p[0] - last[0], p[1] - last[1]) > 2.2) { out.push(pt); last = p; }
    }
    if (out.length < 4) return ring;
    out.push(ring[ring.length - 1]);
    return out;
  });
}

const header = `// Generated by scripts/build-map.mjs. Do not edit by hand.\n`;
const body = `${header}export const MAP_W = ${W};\nexport const MAP_H = ${H};\nexport const MERCATOR = { scale: ${projection.scale()}, tx: ${projection.translate()[0]}, ty: ${projection.translate()[1]} };\n\nexport interface CountyShape { name: string; d: string; cx: number; cy: number }\n\nexport const COUNTIES: CountyShape[] = ${JSON.stringify(counties)};\n`;
writeFileSync(new URL('../src/data/geo/romania.ts', import.meta.url), body);
console.log(`Wrote ${counties.length} counties, ${(body.length / 1024).toFixed(0)} KB`);
